#!/usr/bin/env node
'use strict';

// Render the AppSumo listing markdown into paste-ready plain text.
//
// The .txt is a build output, never a source: credit-meter-truth.test.js guards
// the markdown only, so a hand-maintained second copy could drift from the
// prices production actually charges. Regenerate instead of editing:
//
//   node scripts/render-appsumo-listing.js            # writes the .txt
//   node scripts/render-appsumo-listing.js --stdout   # print, write nothing

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'docs/growth/appsumo-listing-v8.md');
const DEST = SRC.replace(/\.md$/, '.txt');

// Everything below this heading is internal reasoning, not listing text.
const INTERNAL_MARKER = '## Before this is submitted';
// Where buyer-facing copy stops and portal dropdown settings begin.
const SETTINGS_MARKER = '## Classification';

const strip = (s) => s
    .split('\n')
    .map((l) => l.replace(/^>\s?/, ''))
    .join('\n')
    .replace(/\*\*(.+?)\*\*/gs, '$1')
    .replace(/(^|[\s(])\*([^*\n]+)\*/g, '$1$2')
    .replace(/`([^`]+)`/g, '$1')
    // Markdown escapes (\* for a literal footnote asterisk) are source syntax,
    // not copy — left in, the buyer reads "included\*". Runs after the
    // emphasis passes above, which never match an escaped asterisk.
    .replace(/\\([*_`\\])/g, '$1')
    .replace(/^#{1,6}\s*/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

function main() {
    const md = fs.readFileSync(SRC, 'utf8');
    const copyRegion = md.split(INTERNAL_MARKER)[0];

    const fromTitle = copyRegion.slice(copyRegion.indexOf('## Product title'));
    const [buyerFacing, settings] = fromTitle.includes(SETTINGS_MARKER)
        ? [fromTitle.slice(0, fromTitle.indexOf(SETTINGS_MARKER)), fromTitle.slice(fromTitle.indexOf(SETTINGS_MARKER))]
        : [fromTitle, ''];

    const out = [
        'APPSUMO LISTING v8 — PASTE-READY TEXT',
        `Generated from docs/growth/appsumo-listing-v8.md on ${new Date().toISOString().slice(0, 10)}.`,
        'Do not edit this file. Edit the markdown and re-run scripts/render-appsumo-listing.js.',
        '',
        'DO NOT SUBMIT YET — the wallet sold below is not live in production:',
        '  - CREDIT_ALLOWANCE_V3_EFFECTIVE_FROM is unset, so a redemption today still meters at',
        '    50/150/400 while this text sells 200/500/1000. Set the cutover first; see',
        '    "The flip — exact values, exact order" in the markdown.',
        '',
        'Cleared since v7: the $14.99 top-up line (STRIPE_PRICE_ID_CREDITS_TOPUP is set on Render)',
        'and Section 3, API + MCP (/api/v1 and /mcp verified live 2026-09-11).',
        '',
        '='.repeat(72),
        'BUYER-FACING COPY',
        '='.repeat(72),
        '',
        strip(buyerFacing),
        '',
        '='.repeat(72),
        'PORTAL SETTINGS — not listing text, do not paste into a copy field',
        '='.repeat(72),
        '',
        strip(settings),
        ''
    ].join('\n');

    if (process.argv.includes('--stdout')) { process.stdout.write(out); return; }
    fs.writeFileSync(DEST, out);
    console.log(`wrote ${path.relative(ROOT, DEST)} (${out.length} chars)`);
}

main();
