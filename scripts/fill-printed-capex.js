#!/usr/bin/env node
'use strict';
// Capital expenditure read from the printed cash-flow statement.
//
// Why this exists: SEC's XBRL feed does not carry a purchases-of-PP&E concept for every issuer even when the
// printed statement shows the line (ConocoPhillips and NextEra file none for FY2025; Infosys tags only
// retirements). Nothing is estimated here: the row is located by its printed label inside the statement whose
// title says cash flows, the value is the printed cell for the year's own column, and both are kept as the
// receipt. A filing that does not pass the checks below contributes nothing.
//
//   node scripts/fill-printed-capex.js COP NEE CNQ            # dry run, prints what it read
//   node scripts/fill-printed-capex.js --all --write          # every target in the gap list
//   options: --cache DIR  --log FILE  --jobs N  --min-revenue MILLIONS
//
// Targets are the issuers whose latest annual cash statement has operating cash flow but no capex figure and
// that report revenue (a pre-revenue company has no capital spending to find).

const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const BACKEND = path.join(__dirname, '..', 'backend');
const p = require(path.join(BACKEND, 'sec-coverage'));
const ex = require('./extract-html-statements');

const UA = 'StockPortfolio research support@stockportfolio.pro';
const DATA = p.DATA_DIR;
const CAPEX_LINE = /^(?:(?:net|total|gross)\s+)?(?:(?:purchases?|acquisitions?|additions?|payments?|investments?|expenditures?)\s+(?:of|to|for|in|on)\s+)?(?:property,?\s*plant,?\s*(?:and|&)\s*equipment|property\s+(?:and|&)\s+equipment|fixed\s+assets|capital\s+expenditures?|capital\s+spending|plant,?\s*property|oil\s+and\s+gas\s+propert|productive\s+assets)\b/i;
const NOT_CAPEX = /\b(?:depreciation|amorti[sz]ation|disposals?|retirements?|impairment|write-?off|net\s+book|accumulated|non-?cash|through the issuance|in accounts payable|accrued|not yet paid|refunds?)\b/i;
const STATEMENT_TITLE = /cash\s*flows?|cash\s*flow\s*statements?/i;

const clean = (s) => String(s || '').replace(/\u00a0/g, ' ').replace(/\s+/g, ' ').trim();
const parseAmount = (text) => {
    const raw = clean(text);
    if ((raw.match(/\(/g) || []).length !== (raw.match(/\)/g) || []).length) return null;
    const t = raw.replace(/[$,]/g, '');
    if (!t || /^[—–-]$/.test(t) || !/\d/.test(t)) return null;
    const negative = /^\(.*\)$/.test(t) || /^-/.test(t);
    const m = t.replace(/[()]/g, '').match(/-?\d+(?:\.\d+)?/);
    if (!m) return null;
    const v = Number(m[0].replace(/-/g, ''));
    if (!Number.isFinite(v)) return null;
    return negative ? -v : v;
};

function scaleOf(gap) {
    const text = clean(gap);
    const m = text.match(/\(?\s*in\s+(thousands|millions|billions)\b/i) || text.match(/\(?\s*(thousands|millions|billions)\b/i);
    if (!m) return null;
    return { thousands: 1e3, millions: 1e6, billions: 1e9 }[m[1].toLowerCase()];
}

// Years in a header row, in printed order, with the column each occupies.
function headerYears(row) {
    return row.map((cell, i) => {
        const t = clean(cell.text);
        const m = t.match(/\b(19|20)\d{2}\b/);
        return m ? { year: Number(m[0]), col: i } : null;
    }).filter(Boolean);
}

function findCapex(tables, text, knownOcf) {
    for (const table of tables) {
        const gap = clean(text.slice(table.gapStart, table.start)).slice(-400);
        const head = table.rows.slice(0, 3).map((r) => r.map((c) => c.text).join(' ')).join(' ');
        const flat = table.rows.map((r) => r.map((c) => c.text).join(' ')).join(' ');
        // Anchor: the table must hold the statement's own investing total, or be titled as the statement.
        const hasInvesting = table.rows.some((r) => /net cash (?:flows? )?(?:provided by|used in|from)/i.test(clean(r[0]?.text)) && /investing activities/i.test(clean(r[0]?.text)));
        if (!hasInvesting && !STATEMENT_TITLE.test(gap) && !STATEMENT_TITLE.test(head) && !(/investing activities/i.test(flat) && /operating activities/i.test(flat))) continue;
        if (!hasInvesting && !/operating activities/i.test(flat)) continue;
        const scale = scaleOf(gap) || scaleOf(head);
        if (!scale) continue;
        let header = null;
        for (const row of table.rows.slice(0, 6)) {
            const years = headerYears(row);
            if (years.length >= 2 && (!header || years.length > header.years.length)) header = { row, years };
        }
        if (!header) continue;
        const latest = header.years.reduce((a, b) => (b.year > a.year ? b : a));
        const totalRow = (kind) => table.rows.find((r) => /net cash (?:flows? )?(?:provided by|used in|from|generated from|generated by)/i.test(clean(r[0]?.text)) && new RegExp(kind + ' activities', 'i').test(clean(r[0]?.text)));
        const investingRow = totalRow('investing'), operatingRow = totalRow('operating');
        const investingValue = investingRow ? parseAmount(investingRow[latest.col]?.text) : null;
        const operatingValue = operatingRow ? parseAmount(operatingRow[latest.col]?.text) : null;
        // Calibrate the printed scale against the operating cash flow we already hold for that same year: the
        // ratio must be a whole power of a thousand, which also proves the column picked is the right year.
        let printedScale = scale;
        if (operatingValue !== null && Number.isFinite(knownOcf) && knownOcf !== 0) {
            const ratio = Math.abs(knownOcf / operatingValue);
            const power = [1, 1e3, 1e6, 1e9].find((k) => Math.abs(ratio / k - 1) <= 0.02);
            if (!power) continue;
            printedScale = power;
        }
        for (const row of table.rows) {
            const label = clean((row.find((c) => clean(c.text)) || {}).text);
            if (!label || !CAPEX_LINE.test(label) || NOT_CAPEX.test(label)) continue;
            // Values sit to the right of the year labels, one printed cell each, with currency cells and
            // spans in between: take the k-th numeric cell at or after the first year column, where k is the
            // latest year's rank. A "Note" column left of the years cannot be mistaken for a value.
            const firstYearCol = Math.min(...header.years.map((y) => y.col));
            const rank = header.years.slice().sort((a, b) => b.year - a.year).findIndex((y) => y.year === latest.year);
            const numbers = [];
            for (let i = firstYearCol; i < row.length; i++) { const v = parseAmount(row[i]?.text); if (v !== null) numbers.push({ v, cell: row[i] }); }
            const pick = numbers[rank];
            if (!pick) continue;
            const raw = pick.v, cell = pick.cell;
            if (raw === 0) continue;
            const value = -Math.abs(Math.round(raw * printedScale));
            // The capital line is a part of investing, but proceeds (divestitures, asset sales) can leave the
            // net investing total smaller than it: ConocoPhillips' FY2025 capex is $12.6bn against $8.8bn of net
            // investing outflow. Reject only a figure an order of magnitude out of that section's range.
            // Compare against the larger of the two sections' totals: a company that holds large investments can
            // net its investing section close to zero (Infosys: capex $306m against $10m net investing).
            // A line labelled "purchases of property and equipment" that is a rounding error beside the
            // statement's own investing outflows is not this company's capital spending (Sunrun's $1.8m line
            // sits beside $2.5bn of energy-system payments): leave it blank rather than publish a token figure.
            if (investingValue !== null) {
                const section = Math.abs(investingValue * printedScale);
                if (section > 0 && Math.abs(value) < section * 0.05) continue;
            }
            const sections = [investingValue, operatingValue].filter((v) => v !== null).map((v) => Math.abs(v * printedScale));
            const ceiling = sections.length ? Math.max(...sections.map((v) => Math.abs(v))) * 3 : null;
            if (ceiling !== null && ceiling > 0 && Math.abs(value) > ceiling) continue;
            return { value, label, cellText: clean(cell.text), year: latest.year, scale: printedScale, investingValue, title: clean(gap).slice(-120) };
        }
    }
    return null;
}


// Some filers print the cash-flow statement with years down the page (one column per year label, the line
// name in a header cell). Read that shape too: the label comes from the header row, the value from the rows
// whose first cell is the year.
function findCapexTransposed(tables, text, knownOcf) {
    for (const table of tables) {
        const gap = clean(text.slice(table.gapStart, table.start)).slice(-400);
        if (!STATEMENT_TITLE.test(gap) && !table.rows.slice(0, 3).some((r) => STATEMENT_TITLE.test(r.map((c) => c.text).join(' ')))) continue;
        const headRow = table.rows[0] || [];
        const labels = headRow.map((c, i) => ({ i, text: clean(c.text) })).filter((x) => x.text && CAPEX_LINE.test(x.text) && !NOT_CAPEX.test(x.text) && !/\b(?:19|20)\d{2}\b/.test(x.text));
        if (!labels.length) continue;
        const yearRows = table.rows.slice(1).map((r) => ({ year: Number((clean(r[0]?.text).match(/(19|20)\d{2}/) || [])[0]), r })).filter((x) => Number.isFinite(x.year));
        if (yearRows.length < 2) continue;
        const latest = yearRows.reduce((a, b) => (b.year > a.year ? b : a));
        for (const cell of labels) {
            const raw = parseAmount(latest.r[cell.i]?.text);
            if (raw === null || raw === 0) continue;
            const scale = scaleOf(gap) || scaleOf(headRow.map((c) => c.text).join(' '));
            if (!scale) continue;
            const value = -Math.abs(Math.round(raw * scale));
            return { value, label: cell.text, cellText: clean(latest.r[cell.i].text), year: latest.year, scale, investingValue: null, title: clean(gap).slice(-120) };
        }
    }
    return null;
}

async function fetchDoc(url, cacheDir) {
    const file = path.join(cacheDir, url.split('/').slice(-2).join('_'));
    if (fs.existsSync(file)) return fs.readFileSync(file, 'utf8');
    const res = await fetch(url, { headers: { 'User-Agent': UA, accept: 'text/html' }, redirect: 'follow' });
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const text = await res.text();
    fs.mkdirSync(cacheDir, { recursive: true });
    fs.writeFileSync(file, text);
    return text;
}

function targets() {
    const companies = JSON.parse(fs.readFileSync(path.join(DATA, 'us-companies.json'), 'utf8')).companies;
    const byCik = new Map();
    for (const c of companies) if (c.securityType === 'stock' && c.cik) { const k = String(c.cik).padStart(10, '0'); if (!byCik.has(k)) byCik.set(k, []); byCik.get(k).push(c.symbol); }
    const report = JSON.parse(fs.readFileSync(path.join(DATA, 'sec-reporting.json'), 'utf8')).issuers;
    const out = [];
    for (const [cik, symbols] of byCik) {
        const annual = report[cik]?.latestAnnual;
        if (!annual?.primaryDocument) continue;
        let data; try { data = JSON.parse(fs.readFileSync(path.join(DATA, 'sec-financials', cik + '.json'), 'utf8')); } catch (_) { continue; }
        const cash = (data.cash?.annualReports || [])[0];
        const income = (data.income?.annualReports || [])[0];
        if (!cash || cash.operatingCashflow == null || cash.capitalExpenditures != null) continue;
        if (!(income?.totalRevenue > 0)) continue;
        out.push({ cik, symbol: symbols[0], annual, periodEnd: cash.fiscalDateEnding, periodStart: cash.periodStart, revenue: income.totalRevenue, currency: cash.reportedCurrency || income.reportedCurrency || 'USD', sic: String(report[cik]?.sic || ''), operatingCashflow: cash.operatingCashflow });
    }
    return out;
}

function observation(t, read, retrievedAt) {
    const digest = p.digest({ cik: t.cik, accession: t.annual.accessionNumber, value: read.value, periodEnd: t.periodEnd });
    return {
        issuer: t.cik, securitySymbol: t.symbol, field: 'capitalExpenditures',
        definition: `Capital expenditure (printed line "${read.label}")`,
        value: read.value, scale: 1, unit: t.currency || 'USD', currency: t.currency || 'USD',
        periodStart: t.periodStart || null, periodEnd: t.periodEnd, basis: 'annual', historyBasis: 'annual',
        periodDefinition: `Year ended ${t.periodEnd}, column "${read.year}"`,
        accountingBasis: 'US GAAP', scope: 'entity', statement: 'cash', sourceType: 'issuer_release',
        sourceName: 'SEC EDGAR filing (printed cash-flow statement)',
        sourceUrl: t.annual.filingUrl.replace(/[^/]*$/, t.annual.primaryDocument),
        publicationDate: t.annual.filingDate, sourceDataDate: t.annual.filingDate, sourceDateKind: 'publication',
        retrievedAt, sourceVersions: [t.annual.accessionNumber], verificationMethod: 'filing_html_table',
        extractionVersion: '20261104-printedcapex1', state: 'available',
        sourceIds: ['sec-print:' + digest.slice(0, 16)],
        receipt: { statement: read.title, label: read.label, cellText: read.cellText, column: String(read.year), scale: read.scale, document: t.annual.primaryDocument, accession: t.annual.accessionNumber }
    };
}

function writeObservation(t, obs) {
    const file = path.join(DATA, 'supplemental-financials', t.cik + '.json');
    let doc = null;
    try { doc = JSON.parse(fs.readFileSync(file, 'utf8')); } catch (e) { if (e.code !== 'ENOENT') throw e; }
    const obsApi = require(path.join(BACKEND, 'company-observations'));
    if (!obsApi.validSupplement(obs, t.cik)) return { ok: false, why: 'rejected by validSupplement' };
    const kept = (doc?.observations || []).filter((f) => !(f.sourceType === 'issuer_release' && f.field === 'capitalExpenditures' && f.periodEnd === obs.periodEnd && (f.sourceIds || []).some((id) => String(id).startsWith('sec-print:'))));
    const merged = obsApi.reconcile([], [...kept, obs]);
    p.atomicWrite(file, { ...(doc || {}), schemaVersion: 1, issuer: t.cik, cik: t.cik, symbol: doc?.symbol || t.symbol, checkedAt: new Date().toISOString(), refreshStatus: 'success', observations: merged });
    return { ok: updated(kept.length, merged.length) };
}
const updated = (a, b) => b >= a;

async function main() {
    const args = process.argv.slice(2);
    const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
    const cacheDir = path.resolve(opt('--cache', path.join(os.tmpdir(), 'printed-capex')));
    const logFile = opt('--log', null);
    const write = args.includes('--write');
    const all = args.includes('--all');
    const jobs = Math.max(1, Number(opt('--jobs', 4)));
    const symbols = new Set(args.filter((a) => !a.startsWith('--') && !['--cache', '--log', '--jobs', '--min-revenue'].includes(a) && !/^\d+$/.test(a)).map((s) => s.toUpperCase()));
    let list = targets();
    if (!all && symbols.size) list = list.filter((t) => symbols.has(t.symbol));
    else if (!all) { console.error('name symbols, or pass --all'); process.exit(2); }
    const log = [];
    let done = 0, read = 0, rejected = 0;
    await Promise.all(Array.from({ length: jobs }, async () => {
        while (list.length) {
            const t = list.shift();
            const entry = { symbol: t.symbol, cik: t.cik, periodEnd: t.periodEnd, revenue: t.revenue };
            try {
                const html = await fetchDoc(t.annual.filingUrl.replace(/[^/]*$/, t.annual.primaryDocument), cacheDir);
                const { tables, text } = ex.parseTables(html);
                const found = findCapex(tables, text, t.operatingCashflow) || findCapexTransposed(tables, text, t.operatingCashflow);
                if (!found) { entry.result = 'no capex row read'; }
                else {
                    entry.read = { ...found, value: found.value };
                    if (write) { const w = writeObservation(t, observation(t, found, new Date().toISOString())); entry.result = w.ok ? 'written' : 'write rejected'; if (w.ok) read++; }
                    else { entry.result = 'read (dry run)'; read++; }
                }
            } catch (e) { entry.result = 'error: ' + e.message; rejected++; }
            done++;
            log.push(entry);
            if (done % 10 === 0) console.log(JSON.stringify({ done, left: list.length, read, rejected, last: t.symbol }));
        }
    }));
    for (const e of log) console.log(`${(e.symbol || '').padEnd(6)} ${String(e.periodEnd || '').padEnd(11)} ${String(e.result).padEnd(16)} ${e.read ? `${e.read.label} = ${(e.read.value / 1e6).toFixed(2)}M (${e.read.cellText})` : ''}`);
    if (logFile) fs.writeFileSync(logFile, JSON.stringify(log, null, 1));
}
if (require.main === module) main().catch((e) => { console.error(e.message); process.exitCode = 1; });
module.exports = { findCapex, findCapexTransposed, parseAmount, targets, observation };
